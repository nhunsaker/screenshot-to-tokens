// Theme export: build the CSS files a person takes away from the playground, in the browser, in the same formats the
// CLI writes. darkThemeCss = src/stages/dark.js darkCss (tokens.dark.css); tokensCssWith = the run's tokens.css
// (src/stages/emit.js toCss) with the playground's overrides applied; changesCss = only the changed properties.
// ES module with no imports (the playground loads it with import('./theme-css.js'); Node tests import it too).

/** Same rule as contrast.js UNSAFE: a value that could break out of a declaration is never written. */
const UNSAFE = /[;{}<>\\]|url\(|expression\(|@import|javascript:/i
const VAR = /^[a-z0-9-]+$/

/** CSS declarations for a dark proposal: new primitives first, then the rest in proposal order (as dark.js). */
function decls(changes, indent) {
  const sorted = changes.filter((c) => c.isNew).concat(changes.filter((c) => !c.isNew))
  return sorted.filter((c) => VAR.test(c.cssVar) && !UNSAFE.test(c.css)).map((c) => `${indent}--${c.cssVar}: ${c.css};`).join('\n')
}

/**
 * tokens.dark.css, byte for byte the format of dark.js darkCss: the dark values under the system preference (unless
 * the page opts out with data-theme="light") and under an explicit data-theme="dark". `note` goes in the header.
 * @param {{cssVar:string, css:string, isNew?:boolean}[]} changes
 */
export function darkThemeCss(changes, { note = '' } = {}) {
  return [
    `/* Dark theme for tokens.css, generated by screenshot-to-tokens${note ? ` (${note})` : ''}. Review before merging. */`,
    '/* Load after tokens.css. Follows the system setting; data-theme="light" or "dark" on <html> overrides it. */',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]) {',
    decls(changes, '    '),
    '  }',
    '}',
    ':root[data-theme="dark"] {',
    decls(changes, '  '),
    '}',
    '',
  ].join('\n')
}

/** The header note for a dark theme built in the playground: "Argon Dashboard, 2026-11-03, 80 of 87 text pairs pass". */
export function darkNote({ app, date, pass, checked }) {
  return [app, date, checked ? `${pass} of ${checked} text pairs pass` : ''].filter(Boolean).join(', ')
}

const TIER_ORDER = { primitive: 0, semantic: 1, component: 2 }

/**
 * A tokens.css in emit.js toCss's format, from playground tokens ({name, tier, cssVar, value, alias}) when the run's own
 * file is not in tokens.json (older builds). Pure.
 */
export function tokensCssFrom(tokens) {
  const lines = ['/* Generated by screenshot-to-tokens. Review before merging. */', ':root {']
  let tier = null
  const sorted = [...tokens].sort((a, b) => TIER_ORDER[a.tier] - TIER_ORDER[b.tier])
  for (const t of sorted) {
    if (t.tier !== tier) { tier = t.tier; lines.push(`  /* ${tier} */`) }
    const v = t.value ? t.value : `var(--${String(t.alias).trim().replace(/[.\s/]+/g, '-').toLowerCase()})`
    lines.push(`  --${t.cssVar}: ${v};`)
  }
  lines.push('}', '')
  return lines.join('\n')
}

/**
 * The run's tokens.css with `overrides` ({cssVar: value}) applied in place; a property the file does not declare is
 * added in an "/* overrides *\/" block at the end of :root. Unsafe values are skipped. Pure.
 */
export function tokensCssWith(css, overrides) {
  const left = new Map(Object.entries(overrides || {}).filter(([k, v]) => VAR.test(k) && !UNSAFE.test(String(v))))
  const lines = String(css).split('\n').map((line) => {
    const m = /^(\s*)--([a-z0-9-]+)\s*:\s*[^;]*;(.*)$/i.exec(line)
    if (!m || !left.has(m[2])) return line
    const v = left.get(m[2]); left.delete(m[2])
    return `${m[1]}--${m[2]}: ${v};${m[3]}`
  })
  if (left.size) {
    const end = lines.lastIndexOf('}')
    const add = ['  /* overrides */', ...Array.from(left, ([k, v]) => `  --${k}: ${v};`)]
    if (end >= 0) lines.splice(end, 0, ...add)
    else lines.push(':root {', ...add, '}', '')
  }
  return lines.join('\n')
}

/** Only the changed custom properties, as one :root block. Pure. */
export function changesCss(overrides) {
  const d = Object.entries(overrides || {}).filter(([k, v]) => VAR.test(k) && !UNSAFE.test(String(v))).map(([k, v]) => `  --${k}: ${v};`)
  return `/* Token changes from the playground. Paste after tokens.css. */\n:root {\n${d.join('\n')}\n}\n`
}
