// Emit: TokenSet → tokens.css (custom properties, aliases as var()) + tokens.json (DTCG-style).
import { cssVarOf } from '../lib/props.js'

const TYPE = { color: 'color', radius: 'dimension', space: 'dimension', 'font-size': 'dimension', 'line-height': 'dimension', 'font-weight': 'fontWeight', 'font-family': 'fontFamily', shadow: 'shadow' }
const TIER_ORDER = { primitive: 0, semantic: 1, component: 2 }

/** Short hex for display/CSS: drop the "ff" alpha. */
export const cssValue = (v) => (/^#[0-9a-f]{8}$/i.test(v) && v.toLowerCase().endsWith('ff') ? v.slice(0, 7) : v)

/** @param {import('../types.js').TokenSet} set */
export function toCss(set) {
  const lines = ['/* Generated by screenshot-to-tokens. Review before merging. */', ':root {']
  let tier = null
  const sorted = [...set.tokens].sort((a, b) => TIER_ORDER[a.tier] - TIER_ORDER[b.tier])
  for (const t of sorted) {
    if (t.tier !== tier) { tier = t.tier; lines.push(`  /* ${tier} */`) }
    const v = t.value ? cssValue(t.value) : `var(${cssVarOf(t.alias)})`
    lines.push(`  ${cssVarOf(t.name)}: ${v};`)
  }
  lines.push('}', '')
  return lines.join('\n')
}

/** Nested DTCG-ish JSON: { color: { blue: { 600: { $value, $type, $description } } } } */
export function toDtcg(set, clusters) {
  const kindOf = new Map(clusters.map((c) => [c.id, c.kind]))
  const root = {}
  for (const t of set.tokens) {
    const parts = t.name.split('.')
    let node = root
    for (const p of parts.slice(0, -1)) node = node[p] = node[p] && typeof node[p] === 'object' && !('$value' in node[p]) ? node[p] : {}
    node[parts[parts.length - 1]] = {
      $value: t.value ? cssValue(t.value) : `{${t.alias}}`,
      $type: TYPE[kindOf.get(t.clusters[0])] || 'other',
      $description: t.why,
      $extensions: { 'com.metatoy.s2t': { tier: t.tier, clusters: t.clusters } },
    }
  }
  return root
}
